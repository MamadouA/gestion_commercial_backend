interface ProspectionType {
  service: string;
  deadline: Date;
  status: ProspectionStatus;
  clientId: number;
}

const services = [
  "Construction de villa",
  "Rénovation",
  "Extension de bâtiment",
  "Peinture intérieure",
  "Peinture extérieure",
  "Carrelage",
  "Plomberie",
  "Électricité",
  "Étude architecturale",
  "Terrassement",
  "Fondations",
  "Toiture",
  "Isolation",
  "Clôture",
  "Aménagement de bureau",
];

const statuses = [ProspectionStatus.OPENED, ProspectionStatus.WON, ProspectionStatus.LOST];

const randomInt = (min: number, max: number) =>
  Math.floor(Math.random() * (max - min + 1)) + min;

// - generate the prospections
export const generateProspections = (count = 100, clientCount = 50) => {
  return Array.from({ length: count }, () => {
    const deadline = new Date();
    deadline.setDate(deadline.getDate() + randomInt(15, 365));

    return {
      service: services[randomInt(0, services.length - 1)],
      deadline,
      status: statuses[randomInt(0, statuses.length - 1)],
      clientId: randomInt(1, clientCount),
      tenantId: 1,
      authorId: 1,
    };
  });
}


