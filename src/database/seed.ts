 interface OfferType {
  title: string;
  status: OfferStatus;
  amountHT: number;
  amountTVA: number;
  amountTTC: number;
  authorId: number;
  clientId: number;
  tenantId: number;
  deadline: Date;
}
const offerTitles = [
  "Construction d'une villa R+1",
  "Rénovation complète d'une maison",
  "Extension de bureaux",
  "Travaux de plomberie",
  "Installation électrique",
  "Pose de carrelage",
  "Réfection de toiture",
  "Aménagement de magasin",
  "Construction d'un immeuble",
  "Terrassement et fondations",
  "Peinture intérieure",
  "Clôture et portail",
  "Isolation thermique",
  "Étude architecturale",
  "Réhabilitation d'entrepôt",
];

const offerStatuses = [OfferStatus.PENDING, OfferStatus.WON, OfferStatus.LOST];

export const generateOffers = (count = 50, clientCount = 50): OfferType[] => {
  return Array.from({ length: count }, () => {
    const amountHT = randomInt(500000, 50000000);
    const amountTVA = Math.round(amountHT * 0.18);
    const amountTTC = amountHT + amountTVA;

    const deadline = new Date();
    deadline.setDate(deadline.getDate() + randomInt(7, 180));

    return {
      title: offerTitles[randomInt(0, offerTitles.length - 1)],
      status: offerStatuses[randomInt(0, offerStatuses.length - 1)],
      amountHT,
      amountTVA,
      amountTTC,
      authorId: 1,
      clientId: randomInt(1, clientCount),
      tenantId: 1,
      deadline,
    };
  });
}
